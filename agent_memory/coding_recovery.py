"""Operator-frozen unknowns keep full holds; retired inputs can never be retried.

Legacy receipts lack payload hashes. A proof therefore retires the whole
independent execution user and every frozen source span, not an inferred batch.
No proof is generated by request handling. Every new unknown remains blocking.
"""
import hashlib
import json


def digest(value):
    return hashlib.sha256(value.encode()).hexdigest()


def row_digest(row):
    value=dict(row)
    if isinstance(value.get('body'),bytes):
        value['body']={'sha256':hashlib.sha256(value['body']).hexdigest()}
    return digest(json.dumps(value,sort_keys=True,separators=(',',':')))


def is_hash(value):
    return isinstance(value,str) and len(value)==64 and all(c in '0123456789abcdef' for c in value)


class CodingRecovery:
    def __init__(self,path,journal,ledger):
        self.path,self.journal,self.ledger=path,journal,ledger

    def proofs(self):
        if self.path.is_symlink():raise ValueError('recovery proof symlink forbidden')
        if not self.path.exists():return {}
        value=json.loads(self.path.read_text())
        if (set(value)!={'schema','authorization','input_sha256','retired_users','retired_texts','unknowns'}
                or value['schema']!=1 or not value['authorization'] or not is_hash(value['input_sha256'])):
            raise ValueError('explicit frozen Coding recovery required')
        for key in ('retired_users','retired_texts'):
            if not isinstance(value[key],list) or not value[key] or any(not is_hash(x) for x in value[key]):
                raise ValueError('entire independent execution must be retired')
        proofs={}
        for p in value['unknowns']:
            if set(p)!={'fingerprint','row_sha256','attempt_id','reserved_micro_cny'}:
                raise ValueError('invalid frozen unknown')
            row=self.journal.row(p['fingerprint'])
            if (not row or row['scope']!='coding-official-v0.2' or row['state']!='unknown'
                    or row['status'] is not None or row['body'] is not None or row['body_sha'] is not None
                    or row['transport_completed'] or row['attempt_id']!=p['attempt_id']
                    or row_digest(row)!=p['row_sha256']):
                raise ValueError('frozen unknown changed')
            with self.ledger.connect() as db:
                amount=db.execute('select accounted,reserved,status from attempts where id=?',(p['attempt_id'],)).fetchone()
                outcome=db.execute('select category,http_status from provider_observations where attempt_id=?',(p['attempt_id'],)).fetchone()
            reserve=p['reserved_micro_cny']
            if (type(reserve) is not int or reserve<=0 or amount!=(reserve,reserve,'uncertain')
                    or outcome not in [('network_error',None),('timeout',None),('tls_error',None)]):
                raise ValueError('unknown outcome and full money hold must remain')
            if p['fingerprint'] in proofs:raise ValueError('duplicate unknown proof')
            proofs[p['fingerprint']]=dict(p,users=value['retired_users'],texts=value['retired_texts'])
        if not proofs:raise ValueError('empty recovery proof')
        return proofs

    def permits(self,row):
        p=self.proofs().get(row['fingerprint'])
        return bool(p and row_digest(row)==p['row_sha256'])

    def assert_user(self,user):
        if any(digest(user) in p['users'] for p in self.proofs().values()):
            raise ValueError('retired independent execution cannot be replayed')

    def assert_texts(self,texts):
        blocked={h for p in self.proofs().values() for h in p['texts']}
        if any(digest(text) in blocked for text in texts):
            raise ValueError('retired source spans cannot be replayed under another user or batch')
